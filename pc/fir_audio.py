#!/usr/bin/env python3
"""PC side for the Nexys A7 FIR demo: send audio over the USB-UART, receive filtered audio, plot it.
   Protocol: signed 16-bit samples, 2 bytes each, LOW byte first, 8N1, 1,000,000 baud (both directions).
   Examples:
     python fir_audio.py --selftest                       (no board; checks the PC side)
     python fir_audio.py --list-ports
     python fir_audio.py --port COM5 --wav demo_input.wav --bypass    (SW2 UP: serial-path test)
     python fir_audio.py --port COM5 --wav demo_input.wav --mode hpf  (SW1:SW0=01, SW2 down)
"""
import argparse, sys, wave
import numpy as np

from fir_modes_coeffs import MODES      # same numbers the FPGA uses (generated by scripts/design_modes.py)
SWITCH = {'lpf': 'SW1:SW0 = 00', 'hpf': 'SW1:SW0 = 01', 'bpf': 'SW1:SW0 = 10', 'bsf': 'SW1:SW0 = 11'}
CHUNK = 256            # samples per write/read round trip (512 bytes)

def fir_model(x, mode="lpf"):
    """Bit-exact model of the FPGA: 32-tap FIR, then >>15 (floor) and saturate to int16."""
    y = np.convolve(x.astype(np.int64), np.array(MODES[mode], dtype=np.int64))[:len(x)] >> 15
    return np.clip(y, -32768, 32767).astype(np.int16)

def read_wav(path):
    with wave.open(path, 'rb') as w:
        if w.getsampwidth() != 2: sys.exit("WAV must be 16-bit PCM")
        ch, fs, n = w.getnchannels(), w.getframerate(), w.getnframes()
        x = np.frombuffer(w.readframes(n), dtype='<i2').reshape(-1, ch)[:, 0].astype(np.float64)
    return x, fs

def write_wav(path, x, fs):
    with wave.open(path, 'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(fs); w.writeframes(x.astype('<i2').tobytes())

def resample(x, fs_in, fs_out):
    if fs_in == fs_out: return x
    if fs_in > fs_out:                       # crude anti-alias: moving average before decimating
        r = max(1, int(round(fs_in / fs_out)))
        x = np.convolve(x, np.ones(r) / r, mode='same')
    t_out = np.arange(0, len(x) / fs_in, 1.0 / fs_out)
    return np.interp(t_out, np.arange(len(x)) / fs_in, x)

def run_fpga(port, baud, x):
    try: import serial
    except ImportError: sys.exit("pyserial missing: pip install pyserial")
    ser = serial.Serial(port, baud, timeout=3)
    ser.reset_input_buffer(); ser.reset_output_buffer()
    out = np.empty(len(x), dtype=np.int16)
    for i in range(0, len(x), CHUNK):
        c = x[i:i + CHUNK]
        ser.write(c.astype('<i2').tobytes())
        need = 2 * len(c); buf = ser.read(need)
        if len(buf) != need:
            sys.exit(f"TIMEOUT: got {len(buf)} of {need} bytes at sample {i}. Press BTNC (reset), check COM port/cable, retry.")
        out[i:i + len(c)] = np.frombuffer(buf, dtype='<i2')
    ser.close()
    return out

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--port'); ap.add_argument('--baud', type=int, default=1000000)
    ap.add_argument('--wav'); ap.add_argument('--fs', type=int, default=16000, help='processing sample rate (Hz)')
    ap.add_argument('--seconds', type=float, default=4.0)
    ap.add_argument('--bypass', action='store_true', help='SW2 is UP on the board (echo mode)')
    ap.add_argument('--mode', choices=list(MODES), default='lpf', help='filter mode; set the matching SW1:SW0 on the board')
    ap.add_argument('--selftest', action='store_true'); ap.add_argument('--list-ports', action='store_true')
    ap.add_argument('--record', type=float, help='record N seconds from the PC microphone instead of a WAV')
    ap.add_argument('--noshow', action='store_true'); ap.add_argument('--out', default='fir_result')
    a = ap.parse_args()

    if a.list_ports:
        from serial.tools import list_ports
        for p in list_ports.comports(): print(p.device, '-', p.description)
        return
    if a.record:
        try: import sounddevice as sd
        except ImportError: sys.exit("pip install sounddevice  (or use --wav)")
        print(f"Recording {a.record}s ..."); r = sd.rec(int(a.record * a.fs), samplerate=a.fs, channels=1, dtype='int16'); sd.wait()
        x = r[:, 0].astype(np.float64)
    elif a.wav:
        x, fs_in = read_wav(a.wav); x = resample(x, fs_in, a.fs)
    elif a.selftest:
        t = np.arange(int(a.fs * 2)) / a.fs
        x = 12000 * np.sin(2*np.pi*500*t) + 8000 * np.sin(2*np.pi*5000*t)
    else: sys.exit("give --wav FILE, --record N, or --selftest")

    x = x[:int(a.seconds * a.fs)]
    x = x / max(1.0, np.max(np.abs(x))) * 0.5 * 32767      # headroom: worst-case filter gain (sum|h|) is up to ~2.0
    x = np.round(x).astype(np.int16)
    print(f"{len(x)} samples at {a.fs} Hz ({len(x)/a.fs:.2f} s)")

    expected = x.copy() if a.bypass else fir_model(x, a.mode)
    print('bypass test (SW2 up)' if a.bypass else f'mode {a.mode.upper()}: board must have {SWITCH[a.mode]}, SW2 down; press BTNC before running')
    if a.selftest: y = expected.copy(); print("SELFTEST: software model stands in for the board")
    else:
        if not a.port: sys.exit("need --port COMx (see --list-ports)")
        y = run_fpga(a.port, a.baud, x)
    bad = int(np.count_nonzero(y != expected))
    print(f"Hardware vs software model: {len(x)-bad}/{len(x)} samples identical -> {'PASS' if bad == 0 else 'FAIL'}")
    if bad:
        i = int(np.nonzero(y != expected)[0][0]); print(f"first mismatch at sample {i}: got {y[i]} expected {expected[i]}")

    write_wav(a.out + '_input.wav', x, a.fs); write_wav(a.out + '_filtered.wav', y, a.fs)
    import matplotlib
    if a.noshow: matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(3, 1, figsize=(10, 9))
    n = min(len(x), int(0.02 * a.fs)); t = np.arange(n) / a.fs * 1000
    ax[0].plot(t, x[:n], label='input'); ax[0].plot(t, y[:n], label='filtered (FPGA)'); ax[0].set_xlabel('ms'); ax[0].legend(); ax[0].set_title('First 20 ms')
    ax[1].plot(np.arange(len(x)) / a.fs, x, lw=.5, label='input'); ax[1].plot(np.arange(len(y)) / a.fs, y, lw=.5, label='filtered'); ax[1].set_xlabel('s'); ax[1].legend(); ax[1].set_title('Whole clip')
    N = 1 << int(np.floor(np.log2(min(len(x), 32768)))); win = np.hanning(N); f = np.fft.rfftfreq(N, 1 / a.fs)
    for sig, nm in ((x, 'input'), (y, 'filtered')):
        S = 20 * np.log10(np.abs(np.fft.rfft(sig[:N] * win)) + 1e-9); ax[2].plot(f, S, lw=.7, label=nm)
    ax[2].set_xlabel('Hz'); ax[2].set_ylabel('dB'); ax[2].legend(); ax[2].set_title(f'Spectrum, mode {a.mode.upper()}')
    plt.tight_layout(); plt.savefig(a.out + '.png', dpi=110); print(f"saved {a.out}.png, {a.out}_input.wav, {a.out}_filtered.wav")
    if not a.noshow: plt.show()

if __name__ == '__main__': main()
