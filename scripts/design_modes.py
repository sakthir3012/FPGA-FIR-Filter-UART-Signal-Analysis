#!/usr/bin/env python3
"""Designs the 4 symmetric 32-tap filters (LPF = the existing coefficients; HPF/BPF/BSF = windowed ideal responses),
   writes rtl/fir_modes_pkg.sv and pc/fir_modes_coeffs.py from the SAME numbers."""
import numpy as np, os
N = 32; m = np.arange(N) - 15.5; win = np.hamming(N)
H16_LPF = [30,-36,-82,0,183,165,-233,-522,0,951,787,-1064,-2395,0,6154,11628]
def band(f1, f2):   # ideal band [f1,f2] in cycles/sample, linear phase delay 15.5
    w1, w2 = 2*np.pi*f1, 2*np.pi*f2
    return (np.sin(w2*m) - np.sin(w1*m)) / (np.pi*m)
def with_nulls(h, nulls):   # minimum-norm tweak so the response is EXACTLY zero at the given frequencies (cycles/sample)
    C = np.array([np.cos(2*np.pi*fn*m) for fn in nulls])
    return h - C.T @ np.linalg.solve(C @ C.T, C @ h)
def resp(h, f):
    return np.abs(np.array([np.sum(h*np.exp(-2j*np.pi*fi*np.arange(N))) for fi in f]))
f = np.linspace(0, 0.5, 2001)
spec = {  # kind: (ideal, passband regions for gain check, stopband regions)
 'hpf': (lambda: band(0.25, 0.5),                 [(0.30,0.45)],            [(0.0,0.18)]),
 'bpf': (lambda: band(0.15, 0.35),                [(0.20,0.30)],            [(0.0,0.10),(0.40,0.5)]),
 'bsf': (lambda: with_nulls((band(0.0, 0.5) - band(0.15,0.35))*win, [0.245,0.25,0.255])/win,[(0.0,0.10),(0.38,0.45)], [(0.20,0.30)]),
}
def region_max(R, regs, kind):
    v = []
    for a, b in regs: v += list(R[(f>=a)&(f<=b)])
    return max(v) if kind == 'max' else min(v)
sets = {'lpf': np.array(H16_LPF + H16_LPF[::-1], dtype=np.int64)}
for k, (ideal, pb, sb) in spec.items():
    h = ideal() * win
    R = resp(h, f); h = h * 0.95 / region_max(R, pb, 'max')
    q = np.round(h * 32768).astype(np.int64); assert np.array_equal(q, q[::-1]) and np.abs(q).max() < 32767
    sets[k] = q
regs = {'lpf': ([(0,0.15)], [(0.25,0.5)]), **{k: (v[1], v[2]) for k, v in spec.items()}}
for k in ('lpf','hpf','bpf','bsf'):
    R = resp(sets[k]/32768.0, f); pb, sb = regs[k]
    print(f"{k}: passband gain {20*np.log10(region_max(R,pb,'min')):.1f}..{20*np.log10(region_max(R,pb,'max')):.1f} dB,"
          f" stopband worst {20*np.log10(region_max(R,sb,'max')+1e-12):.1f} dB, sum|h|={np.abs(sets[k]).sum()/32768:.2f}")
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
def sv(v): return ("-" if v < 0 else "") + f"16'sd{abs(int(v))}"
rows = ",\n    ".join("'{" + ", ".join(sv(v) for v in sets[k][:16]) + "}" for k in ('lpf','hpf','bpf','bsf'))
open(os.path.join(root,'rtl','fir_modes_pkg.sv'),'w').write(
 "// GENERATED by scripts/design_modes.py - do not edit. mode 0=LPF 1=HPF 2=BPF 3=BSF; first 16 taps, h[31-k]=h[k].\n"
 "package fir_modes_pkg;\n  localparam logic signed [15:0] HM [0:3][0:15] = '{\n    " + rows + "\n  };\nendpackage\n")
open(os.path.join(root,'pc','fir_modes_coeffs.py'),'w').write(
 "# GENERATED by scripts/design_modes.py\nMODES = {\n" + "".join(f"  '{k}': {list(map(int, sets[k]))},\n" for k in ('lpf','hpf','bpf','bsf')) + "}\n")
import matplotlib; matplotlib.use('Agg'); import matplotlib.pyplot as plt
plt.figure(figsize=(9,5))
for k, nm in (('lpf','LPF (SW1:SW0=00)'),('hpf','HPF (01)'),('bpf','BPF (10)'),('bsf','BSF (11)')):
    plt.plot(f, 20*np.log10(resp(sets[k]/32768.0, f)+1e-6), label=nm)
plt.ylim(-80, 5); plt.xlabel('frequency / fs  (x16000 = Hz at fs=16 kHz)'); plt.ylabel('dB'); plt.grid(alpha=.3); plt.legend(); plt.title('Quantized 32-tap responses')
plt.tight_layout(); plt.savefig(os.path.join(root,'docs','mode_responses.png'), dpi=110)
